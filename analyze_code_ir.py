def decode_ir_signal(data_str):
    """将原始IR时序数据解码为字节"""
    values = [int(x) for x in data_str.split()]
    
    ZERO_SPACE_THRESHOLD = 1000  # space < 1000us = 0, >= 1000us = 1
    
    frames = []
    idx = 0
    frame_count = 0
    
    # 每帧需要: header(2) + 8字节*16时序 + end mark(2) = 至少132个值
    while idx < len(values) - 130 and frame_count < 2:
        # 寻找header: mark~9000, space~4500
        if values[idx] >= 8500 and values[idx+1] >= 4000:
            idx += 2  # 跳过header
            
            bits = []
            for byte_idx in range(8):
                byte_val = 0
                for bit in range(8):
                    if idx + 1 >= len(values):
                        break
                    mark = values[idx]
                    space = values[idx + 1]
                    idx += 2
                    # LSB first: space长=1, space短=0
                    if space >= ZERO_SPACE_THRESHOLD:
                        byte_val |= (1 << bit)
                bits.append(byte_val)
            
            frames.append(bits)
            frame_count += 1
            # 跳过end mark和gap
            if idx + 1 < len(values):
                idx += 2
        else:
            idx += 1
    
    return frames


def analyze_frame(name, frame, expected):
    """分析单个帧并对比理论值"""
    if len(frame) < 4:
        print(f"  帧数据不完整")
        return
    
    print(f"\n  第1帧解码: {' '.join([f'0x{b:02X}' for b in frame[:8]])}")
    print(f"    Byte0 二进制: {frame[0]:08b}")
    print(f"      Bit0-3 (模式基础值): 0x{frame[0] & 0x0F:02X}")
    print(f"      Bit4   (电源位):     {'ON (1)' if (frame[0] & 0x10) else 'OFF (0)'}")
    print(f"      Bit5   (风扇位):     {'Fan2 (1)' if (frame[0] & 0x20) else 'Auto/Other (0)'}")
    print(f"      Bit6   (扫风位):     {'ON (1)' if (frame[0] & 0x40) else 'OFF (0)'}")
    print(f"    Byte1 (温度/特殊): 0x{frame[1]:02X} = {frame[1]}")
    if frame[1] != 0x09:
        print(f"      -> 如果temp-16编码: {frame[1] + 16}°C")
    else:
        print(f"      -> 自动模式或关机特殊值")
    print(f"    Byte2:             0x{frame[2]:02X}")
    print(f"    Byte3:             0x{frame[3]:02X}")
    print(f"    Byte4:             0x{frame[4]:02X}")
    print(f"    Byte5:             0x{frame[5]:02X}")
    print(f"    Byte6:             0x{frame[6]:02X}")
    print(f"    Byte7:             0x{frame[7]:02X}")
    
    if expected:
        print(f"\n  与代码理论值对比:")
        for i in range(min(4, len(frame))):
            if i in expected:
                exp = expected[i]
                cap = frame[i]
                diff = cap ^ exp
                status = "MATCH" if diff == 0 else f"MISMATCH (diff=0x{diff:02X})"
                print(f"    Byte{i}: 捕获=0x{cap:02X}, 理论=0x{exp:02X} {status}")


